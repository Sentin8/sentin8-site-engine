// new-site.mjs — scaffolder (design §5): generates a new {vertical}-site
// Docusaurus repo from a site.json inventory. The site engine is consumed
// as a pinned git dependency (site-engine-vX.Y.Z); for local dev it falls
// back to the sibling folder via --local.
//
// Usage:
//   node new-site.mjs --site site.json --out ../bank8/bank8-site --local
//   node new-site.mjs --site site.json --out ../bank8/bank8-site \
//        --org Bank8-dev --tag site-engine-v0.1.0

import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import process from 'node:process';

function parseArgs(argv) {
  const args = { _: [] };
  for (let i = 2; i < argv.length; i++) {
    const a = argv[i];
    if (a === '--local') args.local = true;
    else if (a === '--site') args.site = argv[++i];
    else if (a === '--out') args.out = argv[++i];
    else if (a === '--org') args.org = argv[++i];
    else if (a === '--tag') args.tag = argv[++i];
    else if (a === '--engine-path') args.enginePath = argv[++i];
    else if (a === '--force') args.force = true;
    else args._.push(a);
  }
  return args;
}

const args = parseArgs(process.argv);
if (!args.site || !args.out) {
  console.error('usage: new-site.mjs --site site.json --out DIR [--org ORG] [--tag TAG] [--local [--engine-path PATH]] [--force]');
  process.exit(1);
}

const siteDir = path.resolve(args.out);
if (existsSync(siteDir) && !args.force) {
  console.error(`new-site: ${siteDir} exists (use --force to overwrite files)`);
  process.exit(1);
}
const site = JSON.parse(readFileSync(path.resolve(args.site), 'utf8'));
const vertical = site.vertical;

mkdirSync(siteDir, { recursive: true });
mkdirSync(path.join(siteDir, 'docs'), { recursive: true });
mkdirSync(path.join(siteDir, 'src', 'pages'), { recursive: true });
mkdirSync(path.join(siteDir, 'src', 'css'), { recursive: true });
mkdirSync(path.join(siteDir, 'static', 'img'), { recursive: true });
mkdirSync(path.join(siteDir, '.github', 'workflows'), { recursive: true });

// --local: consume the sibling engine by relative path. Default fits the
// vertical-site layout ({vertical}/{vertical}-site → ../../sentin8/…); the
// platform site passes --engine-path ../sentin8-site-engine explicitly.
const engineDep = args.local
  ? 'file:' + (args.enginePath || '../../sentin8/sentin8-site-engine')
  : `git+https://github.com/Sentin8/sentin8-site-engine.git#${args.tag || 'site-engine-v0.1.0'}`;

/* package.json --------------------------------------------------- */
writeFileSync(
  path.join(siteDir, 'package.json'),
  JSON.stringify(
    {
      name: `${vertical}-site`,
      version: '0.1.0',
      private: true,
      description: `${site.name || vertical} public website (${site.domain || vertical + '.dev'})`,
      license: 'Apache-2.0',
      scripts: {
        harvest: 'node node_modules/@sentin8/site-engine/scripts/harvest.mjs .',
        start: 'docusaurus start',
        build: 'docusaurus build',
        swizzle: 'docusaurus swizzle',
        deploy: 'docusaurus deploy',
        clear: 'docusaurus clear',
        serve: 'docusaurus serve',
        writeTranslations: 'docusaurus write-translations',
        writeHeadingIds: 'docusaurus write-heading-ids',
      },
      dependencies: {
        '@docusaurus/core': '^3.10.0',
        '@docusaurus/preset-classic': '^3.10.0',
        '@docusaurus/theme-mermaid': '^3.10.0',
        '@easyops-cn/docusaurus-search-local': '^0.50.0',
        '@mdx-js/react': '^3.0.0',
        '@mermaid-js/layout-elk': '^0.1.0',
        '@sentin8/site-engine': engineDep,
        react: '^18.0.0',
        'react-dom': '^18.0.0',
      },
    },
    null,
    2,
  ) + '\n',
);

/* docusaurus.config.js -------------------------------------------- */
writeFileSync(
  path.join(siteDir, 'docusaurus.config.js'),
  `// Generated by @sentin8/site-engine new-site.mjs — design §5.
import { makeSiteConfig } from '@sentin8/site-engine';
import site from './site.json';

const config = makeSiteConfig(site, { devPort: ${3000 + ((vertical.length * 7) % 100)} });
export default config;
`,
);

/* sidebars.js ------------------------------------------------------ */
writeFileSync(
  path.join(siteDir, 'sidebars.js'),
  `// Generated by @sentin8/site-engine new-site.mjs — design §5.
import { makeSidebars } from '@sentin8/site-engine';

export default makeSidebars();
`,
);

/* src/css/custom.css ------------------------------------------------ */
writeFileSync(
  path.join(siteDir, 'src', 'css', 'custom.css'),
  `/* Generated by @sentin8/site-engine new-site.mjs. */
@import "@sentin8/site-engine/theme";

:root {
  --site-accent: ${site.accent || '#D4AF37'};
}
`,
);

/* src/pages/index.jsx — landing ------------------------------------ */
const productPrefix = vertical === 'sentin8' ? 'services' : 'products';
const gridComponent = vertical === 'sentin8' ? 'ServiceGrid' : 'ProductGrid';
writeFileSync(
  path.join(siteDir, 'src', 'pages', 'index.jsx'),
  `// Generated by @sentin8/site-engine new-site.mjs — design §4.4/§4.5.
import React from 'react';
import Layout from '@theme/Layout';
import {
  Hero, Section, ${gridComponent}, AppGrid, SdkGrid, VerticalShowcase, SecurityPillars,
} from '@sentin8/site-engine/components';
import site from '../../site.json';

const isPlatform = ${vertical === 'sentin8' ? 'true' : 'false'};
const productPrefix = '${productPrefix}';

export default function Home() {
  return (
    <Layout description={site.tagline}>
      <div className="s8-landing">
        <Hero
          title={site.name}
          tagline={site.tagline}
          actions={[
            { label: 'Read the docs', href: '/docs', primary: true },
            { label: 'Security', href: '/docs/security' },
            { label: 'GitHub', href: 'https://github.com/' + site.org },
          ]}
        />

        {site.units?.length ? (
          <Section
            id="products"
            title={isPlatform ? 'Platform services' : 'Products'}
            lead={isPlatform
              ? 'Every platform service, one plane each: certificates, identity, domain truth, durable change signals.'
              : 'Every service this vertical ships, each owning its own data and API surface.'}
          >
            <${gridComponent}
              items={site.units.map((u) => ({
                name: u.name,
                slug: u.slug,
                summary: u.summary,
                scopes: u.scopes,
                href: '/docs/' + productPrefix + '/' + u.slug + '/',
              }))}
            />
          </Section>
        ) : null}

        {site.apps?.length ? (
          <Section id="apps" title="Apps" lead="User- and staff-facing applications, thin by design — tokens never reach the client.">
            <AppGrid
              items={site.apps.map((a) => ({
                name: a.name,
                slug: a.slug,
                summary: a.summary,
                href: '/docs/apps/' + a.slug + '/',
              }))}
            />
          </Section>
        ) : null}

        {site.sdks?.length ? (
          <Section id="sdks" title="SDKs" lead="Typed facades over every service API — the only supported integration surface.">
            <SdkGrid
              items={site.sdks.map((s) => ({
                name: s.name,
                slug: s.slug,
                summary: s.summary,
                href: s.href,
              }))}
            />
          </Section>
        ) : null}

        {site.starters?.length ? (
          <Section id="starters" title="Starters" lead="The two binaries that bring a fleet to life: bootstrap + supervision.">
            <ServiceGrid
              items={site.starters.map((s) => ({
                name: s.name,
                slug: s.slug,
                summary: s.summary,
                href: '/docs/services/' + s.slug + '/',
              }))}
            />
          </Section>
        ) : null}

        {site.pillars ? (
          <Section id="security" title="Security pillars" lead={site.pillarsLead}>
            <SecurityPillars items={site.pillars} />
          </Section>
        ) : null}

        {site.showcase ? (
          <Section id="verticals" title={site.showcaseTitle || 'The Sentin8 family'} lead={site.showcaseLead}>
            <VerticalShowcase items={site.showcase} />
          </Section>
        ) : null}
      </div>
    </Layout>
  );
}
`,
);

/* .gitignore --------------------------------------------------------- */
writeFileSync(
  path.join(siteDir, '.gitignore'),
  `node_modules/
.docusaurus/
build/
docs/reference/
.tmp/
`,
);

/* docs category scaffolding ------------------------------------------ */
const referenceIndex = `---
sidebar_position: 1
---

# Reference

Architecture deep-dives harvested at build time from each unit's own
repository — README (overview), DESIGN (DDD), BUSINESS (BRD), and the
canonical SECURITY. The repositories stay the source of truth; the
harvester re-renders this section on every build.
`;
const docsSections = [
  ['', { label: site.vertical === 'sentin8' ? 'Platform' : site.name || vertical, position: 1, index: null }],
  ['security', { label: 'Security', position: 2, index: null }],
  [productPrefix, { label: vertical === 'sentin8' ? 'Services' : 'Products', position: 3, index: null }],
  ['apps', { label: 'Apps', position: 4, index: null }],
  ['sdk', { label: 'SDKs', position: 5, index: null }],
  ['developers', { label: 'Developers', position: 6, index: null }],
  ['samples', { label: 'Samples', position: 7, index: null }],
  ['reference', { label: 'Reference (harvested)', position: 60, index: referenceIndex }],
];
for (const [sub, meta] of docsSections) {
  const dir = path.join(siteDir, 'docs', sub);
  mkdirSync(dir, { recursive: true });
  writeFileSync(
    path.join(dir, '_category_.json'),
    JSON.stringify({ label: meta.label, position: meta.position }, null, 2) + '\n',
  );
  if (meta.index) writeFileSync(path.join(dir, 'index.md'), meta.index);
}

/* CNAME ---------------------------------------------------------------- */
mkdirSync(path.join(siteDir, 'static'), { recursive: true });
writeFileSync(
  path.join(siteDir, 'static', 'CNAME'),
  (site.domain || vertical + '.dev') + '\n',
);

/* site.json copy --------------------------------------------------------- */
writeFileSync(path.join(siteDir, 'site.json'), JSON.stringify(site, null, 2) + '\n');

console.log(`new-site: scaffolded ${siteDir}`);
console.log('next: copy the vertical logo to static/img/, run harvest, author docs/, npm install && npm start');