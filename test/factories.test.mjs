// factories.test.mjs - node:test smoke for the config/sidebar factories.

import { test } from 'node:test';
import assert from 'node:assert/strict';
import { makeSiteConfig, makeSidebars } from '../src/index.mjs';

const site = {
  vertical: 'bank8',
  name: 'Bank8',
  org: 'Bank8-dev',
  domain: 'bank8.dev',
  tagline: 'Banking, payments, and open banking on Sentin8',
  accent: '#1B6CA8',
  units: [
    { slug: 'ledger', kind: 'service', name: 'Bank8:Ledger', repo: 'bank8-ledger', summary: 'Core ledger' },
  ],
  apps: [{ slug: 'ebank', kind: 'app', name: 'eBank', repo: 'bank8-ebank', summary: 'Customer banking' }],
  sdks: [],
};

test('makeSiteConfig produces a valid Docusaurus config shape', () => {
  const cfg = makeSiteConfig(site);
  assert.equal(cfg.url, 'https://bank8.dev');
  assert.equal(cfg.title, 'Bank8');
  assert.ok(cfg.presets[0][1].docs.sidebarPath, './sidebars.js');
  assert.ok(cfg.themes.includes('@docusaurus/theme-mermaid'));
  assert.equal(cfg.markdown.mermaid, true);
  // navbar: Products dropdown, Apps dropdown, Security, Developers, Samples, site dropdown, GitHub
  const labels = cfg.themeConfig.navbar.items.map((i) => i.label);
  assert.ok(labels.includes('Products'));
  assert.ok(labels.includes('Apps'));
  assert.ok(labels.includes('Security'));
  assert.ok(labels.includes('GitHub'));
  // footer carries all 8 family links
  const footerSites = cfg.themeConfig.footer.links[1].items.map((i) => i.label);
  assert.ok(footerSites.includes('Sentin8'));
  assert.ok(footerSites.includes('Email8'));
});

test('makeSiteConfig groups vertical accent and custom fields', () => {
  const cfg = makeSiteConfig(site);
  assert.equal(cfg.customFields.accent, '#1B6CA8');
  assert.equal(cfg.customFields.domain, 'bank8.dev');
});

test('footer copyright is the company line, never a per-project variant', () => {
  const cfg = makeSiteConfig(site);
  const cp = cfg.themeConfig.footer.copyright;
  assert.ok(cp.includes('Copyright &copy;'), 'copyright symbol present');
  assert.ok(cp.includes('https://www.logicallymagic.com'), 'company link present');
  assert.ok(cp.includes(String(new Date().getFullYear())), 'current year present');
  assert.ok(cp.includes('<svg'), 'company wordmark svg present');
  assert.ok(!cp.includes('Docusaurus'), 'no per-project variant');
});

test('Quicksand is the default font family, loaded from Google Fonts', () => {
  const cfg = makeSiteConfig(site);
  const linkTags = cfg.headTags.filter((t) => t.tagName === 'link');
  const fontCss = linkTags.find((t) => t.attributes.href?.includes('Quicksand'));
  assert.ok(fontCss, 'Google Fonts stylesheet for Quicksand is injected');
  assert.ok(linkTags.some((t) => t.attributes.href === 'https://fonts.googleapis.com'), 'preconnect present');
});

test('makeSidebars returns the autogenerated docs sidebar', () => {
  const sb = makeSidebars();
  assert.deepEqual(sb, { docs: [{ type: 'autogenerated', dirName: '.' }] });
});

test('platform site uses Services label and services/ routes', () => {
  const cfg = makeSiteConfig({ ...site, vertical: 'sentin8', name: 'Sentin8', domain: 'sentin8.dev' });
  const labels = cfg.themeConfig.navbar.items.map((i) => i.label);
  assert.ok(labels.includes('Services'));
  assert.ok(!labels.includes('Products'));
});