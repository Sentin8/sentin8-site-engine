// makeSidebars-api-root.test.mjs - the top-level API root category contract:
// every per-unit slice nests under ONE API category; other top-level docs
// sections stay untouched; the root links to the first unit-overview doc.

import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, mkdirSync, writeFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { dirname } from 'node:path';

const engineRoot = join(dirname(fileURLToPath(import.meta.url)), '..');

/** Run `makeSidebars()` in a temp site dir carrying the given slice files. */
function runInSiteDir(slices) {
  const cwd = mkdtempSync(join(tmpdir(), 'sb-api-root-'));
  try {
    for (const [slug, json] of Object.entries(slices)) {
      const dir = join(cwd, 'docs', 'api', slug);
      mkdirSync(dir, { recursive: true });
      writeFileSync(join(dir, 'sidebar.json'), JSON.stringify(json));
    }
    const mod = join(cwd, 'run.mjs');
    writeFileSync(
      mod,
      `import { makeSidebars } from ${JSON.stringify(
        'file://' + engineRoot + '/src/index.mjs',
      )};
console.log(JSON.stringify(makeSidebars()));`,
    );
    const res = spawnSync(process.execPath, [mod], { encoding: 'utf8', cwd });
    if (res.status !== 0) throw new Error(res.stderr);
    return JSON.parse(res.stdout);
  } finally {
    rmSync(cwd, { recursive: true, force: true });
  }
}

const UNIT = (slug, overviewId) => [
  {
    type: 'category',
    label: slug,
    items: [{ type: 'doc', id: overviewId, label: 'Overview' }],
  },
];

test('makeSidebars: unit slices nest under ONE top-level API root', () => {
  const sb = runInSiteDir({
    billing: UNIT('billing', 'api/billing/bill-8-billing'),
    payments: UNIT('payments', 'api/payments/bill-8-payments'),
  });
  assert.deepEqual(
    sb.docs.map((i) => (i.type === 'category' ? i.label : i.type)),
    ['autogenerated', 'API'],
  );
  const api = sb.docs[1];
  assert.equal(api.items.length, 2);
  assert.deepEqual(api.items.map((i) => i.label), ['billing', 'payments']);
  // root links to the first unit's Overview doc so the collapsed item opens
  // the reference
  assert.deepEqual(api.link, { type: 'doc', id: 'api/billing/bill-8-billing' });
  assert.equal(api.collapsed, true);
});

test('makeSidebars: a unit without an Overview item still contributes', () => {
  const sb = runInSiteDir({
    payments: [
      { type: 'category', label: 'payments', items: [{ type: 'doc', id: 'api/payments/health' }] },
    ],
  });
  const api = sb.docs[1];
  assert.deepEqual(api.items.map((i) => i.label), ['payments']);
  // no Overview doc on the first unit: the link falls back to the unit
  // category's own link
  assert.deepEqual(api.link, { type: 'doc', id: 'api/payments/health' });
});

test('makeSidebars: a link-only unit (index page, no items) still works', () => {
  const sb = runInSiteDir({
    payments: [
      {
        type: 'category',
        label: 'payments',
        link: { type: 'doc', id: 'api/payments/bill-8-payments' },
        items: [],
      },
    ],
  });
  const api = sb.docs[1];
  assert.deepEqual(api.link, { type: 'doc', id: 'api/payments/bill-8-payments' });
});